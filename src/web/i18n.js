const storageKey = 'chatgpt-bridge-language';
let current = 'zh-CN';
try { current = localStorage.getItem(storageKey) || (navigator.language.startsWith('zh') ? 'zh-CN' : 'en'); } catch {}
if (!['zh-CN', 'en'].includes(current)) current = 'zh-CN';
const reverse = new Map(Object.entries(messages).map(([zh, en]) => [en, zh]));
export const language = () => current;
export function translate(locale, text, values = {}) {
  const source = reverse.get(text) || text;
  const template = locale === 'en' ? messages[source] || source : source;
  return template.replace(/\{(\w+)\}/g, (match, key) => Object.hasOwn(values, key) ? String(values[key]) : match);
}
export const t = (text, values) => translate(current, text, values);

// Capture only shipped UI text and attributes once. Never walk generated history,
// answers, model labels, prompt values or other user content to translate it.
export function initLanguage(onChange) {
  const nodes = [], attributes = [];
  const walker = document.createTreeWalker(document.documentElement, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (node.parentElement.closest('script,style,textarea,pre')) continue;
    const text = node.textContent.trim();
    if (Object.hasOwn(messages, text)) nodes.push([node, node.textContent, text, node.parentElement]);
  }
  for (const element of document.querySelectorAll('[placeholder],[aria-label],[title]')) {
    for (const name of ['placeholder', 'aria-label', 'title']) {
      const value = element.getAttribute(name);
      if (Object.hasOwn(messages, value)) attributes.push([element, name, value]);
    }
  }
  const select = document.getElementById('language');
  function apply() {
    document.documentElement.lang = current;
    for (const [node, original, key, parent] of nodes) {
      if (node.isConnected) node.textContent = original.replace(key, t(key));
      else if (parent.isConnected && !parent.childElementCount && (Object.hasOwn(messages, parent.textContent) || reverse.has(parent.textContent))) parent.textContent = t(parent.textContent);
    }
    for (const [element, name, key] of attributes) element.setAttribute(name, t(key));
    select.value = current;
  }
  select.addEventListener('change', () => {
    current = select.value === 'en' ? 'en' : 'zh-CN';
    try { localStorage.setItem(storageKey, current); } catch {}
    apply();
    onChange();
  });
  apply();
}

