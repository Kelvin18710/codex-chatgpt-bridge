    '任务名称不超过 120 个字符':'Task names must not exceed 120 characters',
    '请先结束对此咨询的跟踪':'Stop tracking this consultation first',
    '配置已在其他页面更新，请重新加载后再保存':'Settings changed in another page. Reload before saving.',
    '咨询已暂停':'Consultations are paused',
